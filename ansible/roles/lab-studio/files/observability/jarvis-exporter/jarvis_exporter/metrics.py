"""Metric definitions shared by all collectors."""

from __future__ import annotations

import time
from typing import Any

from prometheus_client import (
    CollectorRegistry,
    Counter,
    GCCollector,
    Gauge,
    Histogram,
    PlatformCollector,
    ProcessCollector,
)

from .assist import PipelineObservation


LATENCY_BUCKETS = (
    0.025,
    0.05,
    0.1,
    0.2,
    0.3,
    0.5,
    0.75,
    1.0,
    1.5,
    2.0,
    3.0,
    4.0,
    5.0,
    8.0,
    13.0,
    21.0,
    30.0,
)


def _number(value: float | str) -> float:
    normalized = str(value).strip().strip("[]")
    if normalized.lower() in {"n/a", "na", "not supported"}:
        return float("nan")
    return float(normalized)


class Metrics:
    def __init__(self) -> None:
        self.registry = CollectorRegistry()
        ProcessCollector(registry=self.registry)
        PlatformCollector(registry=self.registry)
        GCCollector(registry=self.registry)

        self.build_info = Gauge(
            "jarvis_exporter_build_info",
            "Information about the running jarvis-exporter build.",
            ["version"],
            registry=self.registry,
        )

        self.ollama_enabled = Gauge(
            "jarvis_ollama_benchmark_enabled",
            "Whether manual Ollama benchmarks are enabled.",
            registry=self.registry,
        )
        self.ollama_running = Gauge(
            "jarvis_ollama_benchmark_running",
            "Whether a manual Ollama benchmark is currently running.",
            registry=self.registry,
        )
        self.ollama_requests = Counter(
            "jarvis_ollama_benchmark_requests_total",
            "Number of manual Ollama benchmarks.",
            ["model", "status"],
            registry=self.registry,
        )
        self.ollama_errors = Counter(
            "jarvis_ollama_benchmark_errors_total",
            "Number of failed manual Ollama benchmarks.",
            ["reason"],
            registry=self.registry,
        )
        self.ollama_wall_duration = Histogram(
            "jarvis_ollama_benchmark_wall_duration_seconds",
            "Client-observed duration of manual Ollama benchmarks.",
            ["model"],
            buckets=LATENCY_BUCKETS,
            registry=self.registry,
        )
        self.ollama_ttft = Histogram(
            "jarvis_ollama_benchmark_time_to_first_token_seconds",
            "Client-observed time to the first non-empty Ollama token.",
            ["model"],
            buckets=LATENCY_BUCKETS,
            registry=self.registry,
        )
        self.ollama_last_wall_duration = Gauge(
            "jarvis_ollama_benchmark_last_wall_duration_seconds",
            "Client-observed duration of the last successful benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_ttft = Gauge(
            "jarvis_ollama_benchmark_last_time_to_first_token_seconds",
            "Client-observed time to first token of the last benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_tokens_per_second = Gauge(
            "jarvis_ollama_benchmark_last_tokens_per_second",
            "Generation throughput reported by the last Ollama benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_prompt_tokens = Gauge(
            "jarvis_ollama_benchmark_last_prompt_tokens",
            "Prompt tokens processed by the last Ollama benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_generated_tokens = Gauge(
            "jarvis_ollama_benchmark_last_generated_tokens",
            "Tokens generated by the last Ollama benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_server_duration = Gauge(
            "jarvis_ollama_benchmark_last_server_duration_seconds",
            "Total duration reported by Ollama for the last benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_load_duration = Gauge(
            "jarvis_ollama_benchmark_last_load_duration_seconds",
            "Model load duration reported by Ollama for the last benchmark.",
            ["model"],
            registry=self.registry,
        )
        self.ollama_last_timestamp = Gauge(
            "jarvis_ollama_benchmark_last_success_timestamp_seconds",
            "Unix timestamp of the last successful benchmark.",
            ["model"],
            registry=self.registry,
        )

        self.home_assistant_enabled = Gauge(
            "jarvis_home_assistant_collector_enabled",
            "Whether passive Home Assistant pipeline collection is enabled.",
            registry=self.registry,
        )
        self.home_assistant_up = Gauge(
            "jarvis_home_assistant_collector_up",
            "Whether the last Home Assistant collection succeeded.",
            registry=self.registry,
        )
        self.home_assistant_last_poll = Gauge(
            "jarvis_home_assistant_collector_last_poll_timestamp_seconds",
            "Unix timestamp of the last successful Home Assistant poll.",
            registry=self.registry,
        )
        self.assist_runs = Counter(
            "jarvis_assist_pipeline_runs_total",
            "Number of completed Assist pipeline runs observed.",
            ["pipeline_id", "pipeline_name", "status"],
            registry=self.registry,
        )
        self.assist_errors = Counter(
            "jarvis_assist_pipeline_errors_total",
            "Number of Assist errors observed without message or transcript content.",
            ["pipeline_id", "pipeline_name", "code"],
            registry=self.registry,
        )
        self.assist_stage_duration = Histogram(
            "jarvis_assist_stage_duration_seconds",
            "Duration of privacy-safe Assist pipeline stages.",
            ["pipeline_id", "pipeline_name", "stage"],
            buckets=LATENCY_BUCKETS,
            registry=self.registry,
        )
        self.assist_last_pipeline_duration = Gauge(
            "jarvis_assist_last_pipeline_duration_seconds",
            "Duration of the last completed Assist run.",
            ["pipeline_id", "pipeline_name"],
            registry=self.registry,
        )

        self.nvidia_enabled = Gauge(
            "jarvis_nvidia_collector_enabled",
            "Whether the NVIDIA collector is enabled.",
            registry=self.registry,
        )
        self.nvidia_up = Gauge(
            "jarvis_nvidia_collector_up",
            "Whether the last nvidia-smi collection succeeded.",
            registry=self.registry,
        )
        self.nvidia_last_poll = Gauge(
            "jarvis_nvidia_collector_last_poll_timestamp_seconds",
            "Unix timestamp of the last successful NVIDIA poll.",
            registry=self.registry,
        )
        gpu_labels = ["index", "name"]
        self.gpu_temperature = Gauge(
            "jarvis_gpu_temperature_celsius",
            "NVIDIA GPU temperature in degrees Celsius.",
            gpu_labels,
            registry=self.registry,
        )
        self.gpu_utilization = Gauge(
            "jarvis_gpu_utilization_ratio",
            "NVIDIA GPU utilization as a ratio from zero to one.",
            gpu_labels,
            registry=self.registry,
        )
        self.gpu_memory_used = Gauge(
            "jarvis_gpu_memory_used_bytes",
            "NVIDIA GPU memory currently used in bytes.",
            gpu_labels,
            registry=self.registry,
        )
        self.gpu_memory_total = Gauge(
            "jarvis_gpu_memory_total_bytes",
            "Total NVIDIA GPU memory in bytes.",
            gpu_labels,
            registry=self.registry,
        )
        self.gpu_power = Gauge(
            "jarvis_gpu_power_watts",
            "NVIDIA GPU power draw in watts.",
            gpu_labels,
            registry=self.registry,
        )

    def observe_ollama_success(self, result: Any) -> None:
        model = result.model
        self.ollama_requests.labels(model=model, status="success").inc()
        self.ollama_wall_duration.labels(model=model).observe(result.wall_duration_seconds)
        self.ollama_ttft.labels(model=model).observe(result.time_to_first_token_seconds)
        self.ollama_last_wall_duration.labels(model=model).set(
            result.wall_duration_seconds
        )
        self.ollama_last_ttft.labels(model=model).set(result.time_to_first_token_seconds)
        self.ollama_last_tokens_per_second.labels(model=model).set(
            result.tokens_per_second
        )
        self.ollama_last_prompt_tokens.labels(model=model).set(result.prompt_tokens)
        self.ollama_last_generated_tokens.labels(model=model).set(
            result.generated_tokens
        )
        self.ollama_last_server_duration.labels(model=model).set(
            result.server_duration_seconds
        )
        self.ollama_last_load_duration.labels(model=model).set(
            result.load_duration_seconds
        )
        self.ollama_last_timestamp.labels(model=model).set(time.time())

    def observe_ollama_error(self, model: str, reason: str) -> None:
        self.ollama_requests.labels(model=model or "unknown", status="error").inc()
        self.ollama_errors.labels(reason=reason).inc()

    def observe_assist(
        self,
        pipeline_id: str,
        pipeline_name: str,
        observation: PipelineObservation,
    ) -> None:
        labels = {"pipeline_id": pipeline_id, "pipeline_name": pipeline_name}
        self.assist_runs.labels(**labels, status=observation.status).inc()
        for stage, value in observation.stages.items():
            self.assist_stage_duration.labels(**labels, stage=stage).observe(value)
        if "pipeline" in observation.stages:
            self.assist_last_pipeline_duration.labels(**labels).set(
                observation.stages["pipeline"]
            )
        for code in observation.error_codes:
            self.assist_errors.labels(**labels, code=code).inc()

    def set_gpu(self, values: dict[str, float | str]) -> None:
        labels = {"index": str(values["index"]), "name": str(values["name"])}
        self.gpu_temperature.labels(**labels).set(_number(values["temperature"]))
        self.gpu_utilization.labels(**labels).set(
            _number(values["utilization"]) / 100
        )
        self.gpu_memory_used.labels(**labels).set(
            _number(values["memory_used_mib"]) * 1024 * 1024
        )
        self.gpu_memory_total.labels(**labels).set(
            _number(values["memory_total_mib"]) * 1024 * 1024
        )
        self.gpu_power.labels(**labels).set(_number(values["power_watts"]))
